#!/usr/bin/env python3
"""Generate actual Python aligned-symbol admission and native-release traces."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/l2tunnel-codec/tests/data/aligned-receiver-goldens.tsv"
sys.path.insert(0, str(ROOT / "simulator/src"))
from l2tunnel_sim.aligned_records import AlignedRecordConfig, AlignedRecordReceiver, AlignedRecordTransport  # noqa: E402
from l2tunnel_sim.config import Scenario, Traffic  # noqa: E402
from generate_aligned_body_goldens import native  # noqa: E402


def cases():
    yield "ordered", 1460, 0, 0, [(0, native()), (0, native(sequence=64, identification=1)),
        (0, b"opaque Ethernet"), (0, native(sequence=128, identification=2))], [4, 3, 2, 1, 0, 4, 2]
    yield "short_gap", 1460, 128, 0, [(0, native()), (0, native(0)),
        (0, native(sequence=64, identification=1)), (0, b"z" * 42)], [2, 4, 3, 2, 0, 1, 4]
    yield "channels", 1460, 128, 0, [(0, native()), (1, native()), (0, native(0)),
        (1, native(sequence=64, identification=1))], [4, 5, 3, 2, 0, 1]
    yield "fragments", 72, 0, 0, [(0, native(500)),
        (0, native(500, sequence=500, identification=1))], None
    yield "wrap", 1460, 128, 65534, [(0, native(0)), (0, native(0, identification=1)),
        (0, native(0, identification=2))], [1, 2, 0, 2]
    yield "empty", 1460, 128, 0, [(0, b""), (0, b"raw")], [1, 0]
    yield "new_source_copy", 1460, 128, 0, [(0, native()), (0, native(0)),
        (0, native(sequence=64, identification=1))], [(2, 2), (4, 2), (3, 3), (0, 0), (1, 1), (5, 2)]


def generate():
    rows = ["# aligned-receiver-goldens-v1; generated by tools/generate_aligned_receiver_goldens.py"]
    for name in ("compact.py", "aligned_records.py", "shared_records.py"):
        source = ROOT / "simulator/src/l2tunnel_sim" / name
        rows.append(f"# python_source={source.relative_to(ROOT)}; sha256={hashlib.sha256(source.read_bytes()).hexdigest()}")
    rows.append("# trace\tstep\tsymbol\tshort\tfirst_record\tsource\trecord\tsymbol_hex\tevents\texpected0\texpected1\ttombstones")
    for name, symbol, threshold, first, frames, order in cases():
        sim = SimpleNamespace(now=0, scenario=Scenario(20, 0, mtu=max(128, symbol + 40)), traffic=Traffic(),
                              links=[[SimpleNamespace(rtt=.02)]] * 2, at=lambda *args: None,
                              send=lambda *args: (0, .02))
        config = AlignedRecordConfig(repair_ratio=0, header_profile="tcp_delta",
            authentication_bytes=max(0, 128 - symbol - 40), elide_payload_length=True,
            packed_predictive_records=True, timestamp_pair_dictionary=True,
            independent_short_frame_bytes=threshold)
        sender = AlignedRecordTransport(sim, False, config)
        for channel in (0, 1):
            sender.channel_sequences[channel] = sender.channel_completed[channel] = first
        identities = []
        original = sender._submit_record
        def capture(channel, serial, body):
            before = len(sender.sources)
            original(channel, serial, body)
            identities.extend([(channel, serial)] * (len(sender.sources) - before))
        sender._submit_record = capture
        for channel, frame in frames:
            sender.submit_channel(channel, len(frame), max(0, len(frame) - 66), lambda: None, frame=frame)
        receiver = AlignedRecordReceiver(symbol, threshold)
        for channel in (0, 1):
            receiver.expected[channel] = first
        if order is None:
            order = list(reversed(range(len(sender.sources)))) + [0, len(sender.sources) - 1]
        for step, choice in enumerate(order):
            source, unit = choice if isinstance(choice, tuple) else (choice, choice)
            packet = sender.source_payloads[unit]
            channel, absolute = identities[unit]
            if packet[0] != channel or int.from_bytes(packet[1:3], "big") != absolute & 65535:
                raise ValueError("actual sender identity capture mismatch")
            events = receiver.receive(source, packet)
            encoded_events = ";".join(f"{c}:{serial}:" + ("-" if frame is None else "=" + frame.hex())
                                      for c, serial, frame in events)
            tombstones = ";".join(f"{c}:{serial}" for c, serial in sorted(receiver.early_delivered))
            rows.append("\t".join((name, str(step), str(symbol), str(threshold), str(first), str(source),
                str(absolute), packet.hex(), encoded_events, str(receiver.expected[0]),
                str(receiver.expected[1]), tombstones)))
    return "\n".join(rows) + "\n", len(rows) - 5


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    text, count = generate()
    if args.check:
        if args.output.read_text(encoding="utf-8") != text:
            raise SystemExit("Aligned receiver fixture differs from actual Python source events")
        print(f"Verified {count} actual Python aligned receiver trace steps.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
        print(f"Wrote {count} actual Python aligned receiver trace steps to {args.output}")


if __name__ == "__main__":
    main()
