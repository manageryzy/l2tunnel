#!/usr/bin/env python3
"""Generate byte/state fixtures using the preserved Python CompactHeaderCodec."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "simulator/src/l2tunnel_sim/compact.py"
OUTPUT = ROOT / "crates/l2tunnel-codec/tests/data/tcp-header-goldens.tsv"
sys.path.insert(0, str(ROOT / "simulator/src"))
from l2tunnel_sim.compact import CompactHeaderCodec, tcp_profile_frame  # noqa: E402


def frame(sequence, identification, timestamp, payload, *, source=None, flags=0x18,
          window=65535, acknowledged=9, echoed=7):
    header = bytearray(tcp_profile_frame(
        sequence=sequence, identification=identification, timestamp=timestamp,
        acknowledged=acknowledged, echoed_timestamp=echoed, payload_bytes=0,
        flags=flags, window=window,
    ))
    if source is not None:
        header[26:30] = source
    dynamic = b"".join(header[area] for area in CompactHeaderCodec.dynamic)
    return CompactHeaderCodec._restore(header, dynamic, payload)


def generate():
    initial = frame(0xFFFFFFFE, 65535, 0xFFFFFFFF, b"\x01\x02\xf0")
    wrap = frame(1, 0, 0, b"\x00\xff")
    changed = frame(3, 1, 1, b"\xa5", source=b"\x0a\0\0\x03")
    bad_ip = bytearray(wrap)
    bad_ip[24] ^= 1
    bad_tcp = bytearray(wrap)
    bad_tcp[50] ^= 1
    cases = [
        ("raw_before_context", False, b"\xff" * 17),
        ("initial", False, initial),
        ("modular_wrap", False, wrap),
        ("empty_payload", False, frame(3, 1, 1, b"", flags=0x10)),
        ("retransmission", False, initial),
        ("all_dynamic_fields", False, frame(123456, 123, 512, bytes(range(31)),
                                            flags=0x11, window=20000,
                                            acknowledged=0xFEDCBA98, echoed=65537)),
        ("new_static_context", False, changed),
        ("invalid_ip_checksum", False, bytes(bad_ip)),
        ("invalid_tcp_checksum", False, bytes(bad_tcp)),
        ("unsupported_ethernet", False, b"\xff" * 60),
        ("empty_raw", False, b""),
        ("reset_initial", True, wrap),
        ("reset_raw", True, b"\x45" + bytes(39)),
        ("context_after_raw_reset", False, initial),
    ]
    rows = [
        "# tcp-header-goldens-v1; generated by tools/generate_tcp_header_goldens.py",
        "# python_source=simulator/src/l2tunnel_sim/compact.py",
        "# python_source_sha256=" + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "# profile\tcase\treset\tframe_hex\trecord_hex\tencoder_context_hex\tdecoder_context_hex",
    ]
    for profile, delta in (("tcp_timestamp", False), ("tcp_delta", True)):
        encoder, decoder = CompactHeaderCodec(delta=delta), CompactHeaderCodec(delta=delta)
        for name, reset, native in cases:
            if reset:
                encoder.context = decoder.context = None
            encoded = encoder.encode(native)
            restored = decoder.decode(encoded)
            if restored != [native]:
                raise ValueError(f"Python roundtrip failed: {profile}/{name}")
            rows.append("\t".join((profile, name, str(int(reset)), native.hex(),
                                   encoded.hex(), (encoder.context or b"").hex(),
                                   (decoder.context or b"").hex())))
    return "\n".join(rows) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify fixture without writing")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    text = generate()
    if args.check:
        if args.output.read_text(encoding="utf-8") != text:
            raise SystemExit("TCP header fixture differs from actual Python encoder/state")
        print("Verified 28 Python TCP header byte/state vectors.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
        print(f"Wrote 28 Python TCP header byte/state vectors to {args.output}")


if __name__ == "__main__":
    main()
