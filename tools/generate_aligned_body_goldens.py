#!/usr/bin/env python3
"""Generate body/context goldens by invoking the preserved Python aligned transport."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/l2tunnel-codec/tests/data/aligned-body-goldens.tsv"
sys.path.insert(0, str(ROOT / "simulator/src"))
from l2tunnel_sim.aligned_records import AlignedRecordConfig, AlignedRecordTransport, TIMESTAMP_PAIRS  # noqa: E402
from l2tunnel_sim.compact import CompactHeaderCodec, tcp_profile_frame  # noqa: E402
from l2tunnel_sim.config import Scenario, Traffic  # noqa: E402


def native(payload=64, *, urgent=0, source=None, **fields):
    packet = bytearray(tcp_profile_frame(payload_bytes=payload, **fields))
    packet[52:54] = urgent.to_bytes(2, "big")
    if source is not None:
        packet[26:30] = source
    dynamic = b"".join(packet[area] for area in CompactHeaderCodec.dynamic)
    opaque = bytes((i * 31 + 7) % 256 for i in range(payload))
    return CompactHeaderCodec._restore(packet[:66], dynamic, opaque)


def traces():
    yield "ordinary", 1460, False, False, False, 0, [native(), native(sequence=64, identification=1)]
    for mask in range(32):
        yield f"mask_{mask}", 1460, False, True, False, 0, [native(), native(
            sequence=64, identification=1, flags=0x19 if mask & 1 else 0x18,
            window=0 if mask & 2 else 65535, urgent=int(bool(mask & 4)),
            timestamp=int(bool(mask & 8)), echoed_timestamp=int(bool(mask & 16)))]
    for size in (0, 1, 64):
        for index, (timestamp, echo) in enumerate(TIMESTAMP_PAIRS):
            yield f"pair_{size}_{index}", 1460, True, True, True, 0, [native(size), native(
                size, sequence=size, identification=1, timestamp=timestamp, echoed_timestamp=echo)]
    for size in (0, 1, 127, 128, 1448, 1454, 1455, 1456, 1457, 4000):
        yield f"capacity_{size}", 1460, True, True, True, 0, [native(size), native(
            size, sequence=size, identification=1, timestamp=18, echoed_timestamp=18)]
    for change in ({"payload": 65}, {"identification": 2}, {"sequence": 0},
                   {"acknowledged": 1}, {"timestamp": 20}, {"echoed_timestamp": 16},
                   {"flags": 0x19}, {"window": 0}, {"urgent": 1}):
        fields = dict(payload=64, sequence=64, identification=1, timestamp=18, echoed_timestamp=18)
        fields.update(change)
        escaped = native(**fields)
        fields["sequence"] += fields["payload"]
        fields["identification"] += 1
        fields["timestamp"] += 18
        fields["echoed_timestamp"] += 18
        yield "escape_" + next(iter(change)), 1460, True, True, True, 0, [native(), escaped, native(**fields)]
    yield "wrap", 1460, True, True, True, 0, [
        native(64, sequence=0xFFFFFFF0, identification=65535, acknowledged=0xFFFFFFFF,
               timestamp=0xFFFFFFF6, echoed_timestamp=0xFFFFFFFB),
        native(64, sequence=48, identification=0, acknowledged=0xFFFFFFFF, timestamp=8, echoed_timestamp=12)]
    yield "fallback_refresh", 1460, True, True, True, 0, [native(), b"opaque Ethernet", b"",
        native(sequence=64, identification=1),
        native(sequence=128, identification=2, source=b"\x0a\x01\x02\x03"),
        native(sequence=192, identification=3, source=b"\x0a\x01\x02\x03")]
    yield "short", 1460, True, True, True, 128, [native(), native(0), b"x" * 128,
        native(sequence=64, identification=1), b"", native(63)]
    for symbol in (20, 72, 73):
        yield f"small_symbol_{symbol}", symbol, True, True, True, 0, [native(1), native(1, sequence=1, identification=1)]
    bad = bytearray(native()); bad[50] ^= 1
    yield "bad_checksum", 1460, True, True, True, 0, [native(), bytes(bad), native(sequence=64, identification=1)]


def generate():
    rows = ["# aligned-body-goldens-v1; generated by tools/generate_aligned_body_goldens.py"]
    for name in ("compact.py", "aligned_records.py", "shared_records.py"):
        path = ROOT / "simulator/src/l2tunnel_sim" / name
        rows.append(f"# python_source={path.relative_to(ROOT)}; sha256={hashlib.sha256(path.read_bytes()).hexdigest()}")
    rows.append("# trace\tcase\tsymbol\telide\tpredictive\tdictionary\tshort\tframe_hex\tcontext_hex\tbody_hex\tencoder_context_hex\tdecoder_context_hex")
    for name, symbol, elide, predict, dictionary, short, frames in traces():
        sim = SimpleNamespace(now=0, scenario=Scenario(20, 0, mtu=max(128, symbol + 40)), traffic=Traffic(),
                              links=[[SimpleNamespace(rtt=.02)]] * 2, at=lambda *args: None,
                              send=lambda *args: (0, .02))
        config = AlignedRecordConfig(repair_ratio=0, header_profile="tcp_delta",
            authentication_bytes=max(0, 128 - symbol - 40),
            elide_payload_length=elide, packed_predictive_records=predict,
            timestamp_pair_dictionary=dictionary, independent_short_frame_bytes=short)
        transport = AlignedRecordTransport(sim, False, config)
        captured = []
        original = transport._submit_record
        def capture(channel, serial, body):
            captured.append(bytes(body))
            original(channel, serial, body)
        transport._submit_record = capture
        for case, frame in enumerate(frames):
            captured.clear()
            start = len(transport.sources)
            delivered = []
            transport.submit_channel(0, len(frame), max(0, len(frame) - 66),
                                     delivered.append, frame=frame, deliver_frame=True)
            for source in transport.sources[start:]:
                transport._receive_source(source)
            if delivered != [frame]:
                raise ValueError(f"actual Python receiver failed: {name}/{case}")
            if len(captured) not in (1, 2):
                raise ValueError("expected optional context plus one body")
            context, body = (captured[0], captured[1]) if len(captured) == 2 else (b"", captured[0])
            rows.append("\t".join((name, str(case), str(symbol), str(int(elide)), str(int(predict)),
                str(int(dictionary)), str(short), frame.hex(), context.hex(), body.hex(),
                (transport.channel_codecs[0].context or b"").hex(),
                (transport.receiver.codecs[0].context or b"").hex())))
    return "\n".join(rows) + "\n", len(rows) - 5


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    text, count = generate()
    if args.check:
        if args.output.read_text(encoding="utf-8") != text:
            raise SystemExit("Aligned body fixture differs from actual Python source output")
        print(f"Verified {count} actual Python aligned body/context vectors.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8")
        print(f"Wrote {count} actual Python aligned body/context vectors to {args.output}")


if __name__ == "__main__":
    main()
